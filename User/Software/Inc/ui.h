#ifndef __UI_H
#define __UI_H

/*==============================================================
 *  OLED 调参显示
 *
 *  ⚠️ OLED 走软件 I2C：一个字符约 3~4 ms，一整行约 40 ms。
 *     所以：
 *       1) 每次只刷一行（4 行轮转），单次阻塞 ≤ 45 ms；
 *       2) 停车时 100 ms 刷一行，跑车时 500 ms 刷一行（约 8% 占用）；
 *       3) 按键后调 Ui_RefreshNow() 立即重画，代替蜂鸣提示；
 *       4) 比赛时把 UI_ENABLE 改成 0，代码全部编译掉，零开销。
 *==============================================================*/

#define UI_ENABLE       1       /* 1 = 打开显示，0 = 完全关闭 */

void Ui_Init(void);             /* 上电调用一次               */
void Ui_Refresh(void);          /* 每 100 ms 调用一次（内部降频） */
void Ui_RefreshNow(void);       /* 立即重画 4 行（按键后用）   */

#endif /* __UI_H */
